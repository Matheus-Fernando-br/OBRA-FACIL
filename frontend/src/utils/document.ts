/* Validação de CPF e CNPJ pelos dígitos verificadores (Receita Federal). */

export function isValidCPF(value: string) {
  const cpf = value.replace(/\D/g, "");
  if (cpf.length !== 11 || /^(\d)\1{10}$/.test(cpf)) return false;

  const digit = (len: number) => {
    let sum = 0;
    for (let i = 0; i < len; i++) sum += Number(cpf[i]) * (len + 1 - i);
    const rest = (sum * 10) % 11;
    return rest === 10 ? 0 : rest;
  };

  return digit(9) === Number(cpf[9]) && digit(10) === Number(cpf[10]);
}

export function isValidCNPJ(value: string) {
  const cnpj = value.replace(/\D/g, "");
  if (cnpj.length !== 14 || /^(\d)\1{13}$/.test(cnpj)) return false;

  const digit = (len: number) => {
    const weights = len === 12 ? [5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2] : [6, 5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2];
    const sum = weights.reduce((acc, w, i) => acc + Number(cnpj[i]) * w, 0);
    const rest = sum % 11;
    return rest < 2 ? 0 : 11 - rest;
  };

  return digit(12) === Number(cnpj[12]) && digit(13) === Number(cnpj[13]);
}

/** Mensagem de erro (ou null) para CPF/CNPJ digitado. */
export function validateDocument(value: string): string | null {
  const digits = value.replace(/\D/g, "");
  if (digits.length === 11) return isValidCPF(digits) ? null : "CPF inválido. Confira os números.";
  if (digits.length === 14) return isValidCNPJ(digits) ? null : "CNPJ inválido. Confira os números.";
  return "O CPF deve ter 11 dígitos e o CNPJ, 14.";
}
